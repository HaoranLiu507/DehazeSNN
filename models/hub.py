"""
Hugging Face Hub integration for DehazeSNN.

Provides DehazeSNNHub, a thin wrapper around the DehazeSNN architecture that
inherits PyTorchModelHubMixin for easy `from_pretrained` / `push_to_hub` support.

Usage (loading from Hub):
    from models.hub import DehazeSNNHub
    model = DehazeSNNHub.from_pretrained("FengShaner/DehazeSNN")  # default: L + RESIDE-ITS
    model = DehazeSNNHub.from_pretrained("FengShaner/DehazeSNN", revision="m-reside-6k")

Usage (saving locally / pushing):
    model.save_pretrained("./my-checkpoint")
    model.push_to_hub("your-username/your-repo")
"""

from huggingface_hub import PyTorchModelHubMixin

from .DehazeSNN import DehazeSNN


# Hyperparameter presets per variant (mirrors build_M_model / build_L_model in __init__.py)
VARIANT_CONFIGS = {
    "S": {
        "embed_dims": [24, 48, 96, 48, 24],
        "depths": [2, 4, 8, 4, 2],
    },
    "M": {
        "embed_dims": [24, 48, 96, 48, 24],
        "depths": [8, 12, 16, 12, 8],
    },
    "L": {
        "embed_dims": [24, 48, 96, 48, 24],
        "depths": [8, 16, 32, 16, 8],
    },
}

# Shared defaults (same across all variants)
_SHARED_DEFAULTS = {
    "in_chans": 3,
    "mlp_ratio": [4.0, 4.0, 4.0, 4.0, 4.0],
    "lif_bias": True,
    "drop_path_rate": 0.1,
    "patch_norm": True,
    "lif": 4,
    "lif_fix_tau": False,
    "lif_fix_vth": False,
    "lif_init_tau": 0.25,
    "lif_init_vth": 0.25,
}


class DehazeSNNHub(
    DehazeSNN,
    PyTorchModelHubMixin,
    repo_url="https://github.com/FengShaner/DehazeSNN",
    pipeline_tag="image-to-image",
    license="mit",
):
    """
    DehazeSNN with Hugging Face Hub integration.

    All constructor arguments are JSON-serializable so that `config.json` is
    automatically generated by `save_pretrained`.

    Parameters
    ----------
    variant : str
        One of "S", "M", "L". Determines embed_dims and depths.
    dataset : str, optional
        Informational only; stored in config for provenance (e.g., "RESIDE-ITS").
    **kwargs
        Override any of the shared defaults (lif, lif_init_tau, etc.).
    """

    def __init__(
        self,
        variant: str = "L",
        dataset: str = "",
        **kwargs,
    ):
        if variant not in VARIANT_CONFIGS:
            raise ValueError(f"Unknown variant '{variant}'. Choose from {list(VARIANT_CONFIGS)}")

        # Merge variant-specific + shared defaults + user overrides
        cfg = {**_SHARED_DEFAULTS, **VARIANT_CONFIGS[variant], **kwargs}

        # Store for config.json serialization (PyTorchModelHubMixin reads __init__ args)
        self.variant = variant
        self.dataset = dataset

        super().__init__(**cfg)

